// Writes lib/token.js: the GitHub access key built into the launcher, so it can download from
// private game repos. The key comes from the OL_GITHUB_TOKEN environment variable (a GitHub Actions
// secret in CI). lib/token.js is git-ignored: the key never goes into the repository.
//
// The key is only scrambled, not hidden: anyone with the exe can recover it. Give it read-only
// access to the game repos and nothing else.

const fs = require('fs');
const path = require('path');

const out = path.join(__dirname, '..', 'lib', 'token.js');
const key = (process.env.OL_GITHUB_TOKEN || '').trim();

if (!key) {
  fs.writeFileSync(out, '// No access key in this build: only public game repos can be downloaded.\nmodule.exports = () => null;\n');
  console.warn('[inject-token] OL_GITHUB_TOKEN is not set: this build can only download public repos.');
  process.exit(0);
}

const mask = Array.from({ length: 32 }, () => Math.floor(Math.random() * 256));
const data = Array.from(Buffer.from(key, 'utf8'), (b, i) => b ^ mask[i % mask.length]);
fs.writeFileSync(
  out,
  `// Generated by scripts/inject-token.js at build time. Do not commit.
const m = ${JSON.stringify(mask)};
const d = ${JSON.stringify(data)};
module.exports = () => Buffer.from(d.map((b, i) => b ^ m[i % m.length])).toString('utf8');
`
);
console.log(`[inject-token] built-in access key added (${key.length} characters).`);
